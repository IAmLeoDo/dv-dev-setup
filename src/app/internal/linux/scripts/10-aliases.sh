# shellcheck shell=bash
# shellcheck disable=SC2016 # Initialization expands HOME in the user's shell.
# shellcheck disable=SC2154 # Alias arrays are validated by the setup orchestrator.
alias_directory="$HOME/.config/dv"
alias_file="$alias_directory/aliases.bash"
alias_marker='# Generated by dv-dev-setup: Bash aliases'
if [[ -L $alias_file || ( -e $alias_file && ! -f $alias_file ) ]]; then
    die 'Alias file must be a regular file: ~/.config/dv/aliases.bash'
fi
if [[ -f $alias_file ]]; then
    IFS= read -r first_line < "$alias_file" || true
    [[ $first_line == "$alias_marker" ]] || die 'Existing ~/.config/dv/aliases.bash is unmanaged; move it aside before setup'
fi
if [[ ${DV_DRY_RUN:-false} == true ]]; then
    log "Would write ${#DV_ALIAS_NAMES[@]} Bash aliases to $alias_file"
    for index in "${!DV_ALIAS_NAMES[@]}"; do
        log "  ${DV_ALIAS_NAMES[$index]} -> ${DV_ALIAS_TARGETS[$index]}"
    done
else
    mkdir -p -- "$alias_directory"
    (
        # Write atomically so failed writes preserve the previous file.
        alias_temp=$(mktemp "$alias_directory/.aliases.XXXXXX")
        trap 'rm -f -- "$alias_temp"' EXIT
        {
            printf '%s\n' "$alias_marker"
            for index in "${!DV_ALIAS_NAMES[@]}"; do
                target=${DV_ALIAS_TARGETS[$index]}
                if [[ $target == dv\ * ]]; then
                    printf -v entrypoint '%q' "$DV_TOOLS_ROOT/app/dev.sh"
                    target="bash $entrypoint ${target#dv }"
                fi
                printf 'alias %s=%q\n' "${DV_ALIAS_NAMES[$index]}" "$target"
            done
        } > "$alias_temp"
        mv -f -- "$alias_temp" "$alias_file"
    )
fi
append_once "$HOME/.bashrc" '[ ! -f "$HOME/.config/dv/aliases.bash" ] || . "$HOME/.config/dv/aliases.bash"'
if [[ ${DV_DRY_RUN:-false} != true ]]; then
    log "Configured ${#DV_ALIAS_NAMES[@]} Bash aliases in $alias_file"
    log 'Activate aliases in your CURRENT Bash terminal by running:'
    log '  source "$HOME/.config/dv/aliases.bash"'
    log 'Or open a new interactive Bash shell. Setup cannot change its parent shell.'
fi
